// Generates lib/snap-retailers.ts — how many SNAP-authorized retailers each
// state has, from USDA's own SNAP Retailer Locator feature service.
//
// Run when the figures should be refreshed, NOT on every build:
//   node scripts/gen-retailer-counts.mjs
//
// Same pattern as the map paths and the self-hosted fonts: fetch once, commit
// the artifact, ship no runtime dependency. The alternative — calling ArcGIS
// from the page — would put a third-party host in the critical path of a page
// that has to be fast, server-rendered and crawlable, and would need a CSP hole
// to do it.
//
// ONE request: the service will group and count server-side, so we pull 53
// numbers rather than 250,000 rows we would then have to count ourselves.

import { writeFileSync } from "node:fs";

const SERVICE =
  "https://services1.arcgis.com/RLQu0rK7h4kbsBq5/arcgis/rest/services/" +
  "snap_retailer_location_data/FeatureServer/0/query";

const params = new URLSearchParams({
  where: "1=1",
  groupByFieldsForStatistics: "State",
  outStatistics: JSON.stringify([
    { statisticType: "count", onStatisticField: "ObjectId", outStatisticFieldName: "n" },
  ]),
  f: "json",
});

const res = await fetch(`${SERVICE}?${params}`);
if (!res.ok) throw new Error(`ArcGIS returned ${res.status}`);
const data = await res.json();
if (!data.features?.length) throw new Error("no features returned");

const counts = {};
for (const f of data.features) {
  const { State, n } = f.attributes;
  if (State && typeof n === "number") counts[State.toUpperCase()] = n;
}

const total = Object.values(counts).reduce((a, b) => a + b, 0);
const codes = Object.keys(counts).sort();
// A date, not a timestamp: the figure is refreshed by hand and "as of" is the
// honest granularity. Passed in so the file is reproducible.
const asOf = process.env.AS_OF ?? new Date().toISOString().slice(0, 10);

const body = `// GENERATED by scripts/gen-retailer-counts.mjs — do not edit by hand.
//
// SNAP-authorized retailers per state, from USDA's SNAP Retailer Locator
// feature service. ${codes.length} jurisdictions, ${total.toLocaleString("en-US")} stores.
//
// These are STORE COUNTS, not a measure of how easy it is to reach one. A rural
// state with few stores is not necessarily badly served, and a dense one is not
// necessarily well served — anything the UI says about this has to stay on the
// right side of that line.
//
// Source: services1.arcgis.com/.../snap_retailer_location_data/FeatureServer/0

export const RETAILERS_AS_OF = "${asOf}";
export const RETAILER_TOTAL = ${total};
export const RETAILERS_BY_STATE: Record<string, number> = ${JSON.stringify(counts, null, 0)};
`;

writeFileSync(new URL("../lib/snap-retailers.ts", import.meta.url), body);
console.log(`wrote ${codes.length} jurisdictions, ${total} retailers, as of ${asOf}`);
