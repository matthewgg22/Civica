// County-level §10102 / §10105 exposure estimates for all 58 CA counties.
//
// Used by:
//   * /cdss → CountyLeaderboard (ranks all 58 counties by estimated penalty
//     exposure — the headline B2G slide that drives county engagement)
//   * /county-demo/[county] → CountyExposurePanel (public, per-county view)
//
// Methodology — read before changing anything below:
//
//   caseloadShare
//     county's share of statewide CalFresh applications, rolling 8-month
//     average sourced from CDSS CF 296 ("CalFresh Monthly Caseload"),
//     Jul 2025 – Feb 2026. Application volume is a PROXY for active
//     caseload share — counties with high inflow have high relative
//     CalFresh-eligible population. Real active-caseload data is
//     published as CF 358; swap when that ingest lands.
//
//   estimatedExposureDollars
//     caseloadShare × $510M (CA's §10105 cumulative FY2026–FY2028 federal
//     admin-match penalty exposure, per section10105.ts). Assumes county
//     PER tracks state PER proportionally. A real county PER measurement
//     would replace this — but per-county PER is FOIA-only.
//
//   ageGapEstimate
//     caseloadShare × 325,000 (midpoint of the design doc's 250K–400K
//     statewide newly-in-scope estimate under §10102 age-band changes).
//
//   monthlyApplications
//     8-month time series Jul 2025 – Feb 2026 from CF 296. Used by the
//     leaderboard's per-county sparkline. APPLICATION_MONTHS exposes the
//     month labels in the same order.
//
// Last refreshed: 2026-05-22 (CF 296 FY 2025-26 export, updated 2026-04-13).
//
// To regenerate after a new CF 296 publication:
//   1. Download the new xlsx from cdss.ca.gov
//   2. Re-run scripts/build-county-exposure.py (TODO: check in)
//   3. Replace the RAW block below
//   4. Update "Last refreshed" date + the methodology window
//
// IMPORTANT: keep this file self-contained. Do not depend on caCounties.ts —
// that file handles FIPS resolution for live packet data and changes to its
// shape would couple the public demo to internal data flows.

