const BY_SLUG: Readonly<Record<string, CountyExposureData>> = Object.fromEntries(
  RAW.map((c) => [c.slug, c]),
);

/** Look up a county's exposure row by slug. Returns null when no match. */
export function getCountyExposure(slug: string): CountyExposureData | null {
  return BY_SLUG[slug] ?? null;
}

/** All 58 counties in the order they appear in the source file (by share desc). */
export function listSupportedCounties(): readonly CountyExposureData[] {
  return RAW;
}

/** All 58 counties ranked by estimated cumulative §10105 penalty exposure
 *  (descending). Drives the CDSS leaderboard. */
export function rankedByExposure(): readonly CountyExposureData[] {
  return [...RAW].sort(
    (a, b) => b.estimatedExposureDollars - a.estimatedExposureDollars,
  );
}
